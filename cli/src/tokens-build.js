// craft tokens build: emit design tokens (primitive -> semantic -> component, per theme) as
// CSS custom properties, a Tailwind v3 preset, and a Tailwind v4 @theme stylesheet.
// Output is a pure function of the token file: same input, byte-identical output (ADR-0016).
// No palette is added: only what the token file declares is emitted.
import { resolve as resolveToken, checkReferences } from './tokens.js';

/** @typedef {import('./tokens.js').Tokens} Tokens */
/** @typedef {{ name: string, content: string }} OutFile */
/** @typedef {'css' | 'v4'} Target */

export const HEADER = 'generated by craft tokens build; do not edit';
const REF = /^\{([a-zA-Z][a-zA-Z0-9-]*(?:\.[a-zA-Z0-9-]+)+)\}$/;
/** Characters that could end a declaration or a block, or close a comment or a script. */
const UNSAFE = /[;{}\n\r\\]|\/\*|\*\/|<\//;

/**
 * Tailwind mapping per token group (semantic group names first, then common primitive
 * group names). `kind: 'motion'` splits by value: durations vs easing curves.
 * @type {Record<string, { v3?: string, v4?: string, literal?: boolean, kind?: 'motion' }>}
 */
const GROUPS = {
  color: { v3: 'colors', v4: 'color' },
  space: { v3: 'spacing', v4: 'spacing' },
  spacing: { v3: 'spacing', v4: 'spacing' },
  font: { v3: 'fontFamily', v4: 'font' },
  fontFamily: { v3: 'fontFamily', v4: 'font' },
  text: { v3: 'fontSize', v4: 'text' },
  fontSize: { v3: 'fontSize', v4: 'text' },
  leading: { v3: 'lineHeight', v4: 'leading' },
  lineHeight: { v3: 'lineHeight', v4: 'leading' },
  weight: { v3: 'fontWeight', v4: 'font-weight' },
  fontWeight: { v3: 'fontWeight', v4: 'font-weight' },
  radius: { v3: 'borderRadius', v4: 'radius' },
  elevation: { v3: 'boxShadow', v4: 'shadow' },
  shadow: { v3: 'boxShadow', v4: 'shadow' },
  motion: { kind: 'motion' },
  duration: { kind: 'motion' },
  easing: { kind: 'motion' },
  breakpoint: { v3: 'screens', v4: 'breakpoint', literal: true }
};

/** kebab-case a group name for CSS: fontSize -> font-size. */
const kebab = (/** @type {string} */ s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

/**
 * Is a motion value a duration (otherwise an easing curve)?
 * @param {string | number} v
 */
const isDuration = (v) => /^\d*\.?\d+m?s$/.test(String(v).trim());

/**
 * CSS custom property name for a token path.
 * css: primitives are --primitive-<group>-<name>, semantic --<group>-<name>, component --<component>-<name>.
 * v4: semantic groups that map to a Tailwind v4 namespace use it (space -> --spacing-*).
 * @param {Tokens} tokens
 * @param {string} path dotted, e.g. semantic.color.surface
 * @param {Target} target
 * @returns {string}
 */
export function varName(tokens, path, target) {
  const [layer, group, ...rest] = path.split('.');
  const name = rest.join('-');
  if (layer === 'primitive') return `--primitive-${kebab(group)}-${name}`;
  if (layer === 'component') return `--${kebab(group)}-${name}`;
  if (target === 'v4') {
    const g = GROUPS[group];
    if (g?.kind === 'motion') {
      const v = resolveToken(tokens, path, tokens.themes[0]);
      if (!isDuration(v)) return `--ease-${name}`;
    } else if (g?.v4) return `--${g.v4}-${name}`;
  }
  return `--${kebab(group)}-${name}`;
}

/**
 * CSS value for a raw token value: references become var(), literals pass through.
 * @param {Tokens} tokens
 * @param {string | number} raw
 * @param {Target} target
 * @returns {string}
 */
function cssValue(tokens, raw, target) {
  const m = typeof raw === 'string' ? REF.exec(raw.trim()) : null;
  if (m) return `var(${varName(tokens, m[1], target)})`;
  return String(raw);
}

/**
 * Validate everything the emitters rely on. Returns human-readable problems.
 * @param {Tokens} tokens
 * @returns {string[]}
 */
export function buildProblems(tokens) {
  const problems = [...checkReferences(tokens)];
  /** @type {Map<string, string>} */
  const seen = new Map();
  for (const target of /** @type {Target[]} */ (['css', 'v4'])) {
    seen.clear();
    for (const [layer, groups] of Object.entries({ primitive: tokens.primitive, semantic: tokens.semantic, component: tokens.component ?? {} })) {
      for (const [group, entries] of Object.entries(groups)) {
        for (const [key, value] of Object.entries(entries)) {
          const path = `${layer}.${group}.${key}`;
          const values = value !== null && typeof value === 'object' ? Object.values(value) : [value];
          for (const v of values) if (typeof v === 'string' && !REF.test(v.trim()) && UNSAFE.test(v)) problems.push(`${path}: value ${JSON.stringify(v)} contains characters that are not allowed in a CSS value (; { } \\ newline or comment markers).`);
          let name;
          try {
            name = varName(tokens, path, target);
          } catch {
            continue; // reported by checkReferences
          }
          const other = seen.get(name);
          if (other) problems.push(`${path} and ${other} both become ${name}${target === 'v4' ? ' in tailwind.v4.css' : ''}; rename one of them.`);
          else seen.set(name, path);
        }
      }
    }
  }
  return [...new Set(problems)];
}

/**
 * Declarations for one layer and theme. With `onlyThemed`, only tokens whose value is a
 * per-theme object are included (the theme override blocks).
 * @param {Tokens} tokens
 * @param {'primitive' | 'semantic' | 'component'} layer
 * @param {string} theme
 * @param {Target} target
 * @param {boolean} onlyThemed
 * @param {(group: string, key: string) => boolean} [include]
 * @returns {string[]}
 */
function declarations(tokens, layer, theme, target, onlyThemed, include = () => true) {
  /** @type {string[]} */
  const out = [];
  for (const [group, entries] of Object.entries(tokens[layer] ?? {})) {
    for (const [key, value] of Object.entries(entries)) {
      if (!include(group, key)) continue;
      const themed = value !== null && typeof value === 'object';
      if (onlyThemed && !themed) continue;
      const raw = themed ? /** @type {Record<string, string | number>} */ (value)[theme] : value;
      out.push(`  ${varName(tokens, `${layer}.${group}.${key}`, target)}: ${cssValue(tokens, raw, target)};`);
    }
  }
  return out;
}

/**
 * Theme blocks: the default theme is themes[0] (in :root); "dark" also follows
 * prefers-color-scheme unless a data-theme attribute pins a theme.
 * @param {Tokens} tokens
 * @param {Target} target
 * @param {(group: string, key: string) => boolean} [include]
 * @returns {string[]}
 */
function themeBlocks(tokens, target, include) {
  /** @type {string[]} */
  const out = [];
  for (const theme of tokens.themes.slice(1)) {
    const decl = [...declarations(tokens, 'semantic', theme, target, true, include), ...declarations(tokens, 'component', theme, target, true)];
    if (!decl.length) continue;
    if (theme === 'dark') out.push('', '@media (prefers-color-scheme: dark) {', '  :root:not([data-theme]) {', ...decl.map((d) => `  ${d}`), '  }', '}');
    out.push('', `[data-theme="${theme}"] {`, ...decl, '}');
  }
  const first = tokens.themes[0];
  const firstDecl = [...declarations(tokens, 'semantic', first, target, true, include), ...declarations(tokens, 'component', first, target, true)];
  if (tokens.themes.length > 1 && firstDecl.length) out.push('', `[data-theme="${first}"] {`, ...firstDecl, '}');
  return out;
}

/**
 * @param {Tokens} tokens
 * @returns {string}
 */
export function emitCss(tokens) {
  const first = tokens.themes[0];
  return [
    `/* ${HEADER}. Source: ${tokens.name}. Default theme: ${first}${tokens.themes.length > 1 ? `; others: ${tokens.themes.slice(1).map((t) => `[data-theme="${t}"]`).join(', ')}` : ''}. */`,
    '',
    ':root {',
    '  /* primitive */',
    ...declarations(tokens, 'primitive', first, 'css', false),
    '  /* semantic */',
    ...declarations(tokens, 'semantic', first, 'css', false),
    ...(tokens.component ? ['  /* component */', ...declarations(tokens, 'component', first, 'css', false)] : []),
    '}',
    ...themeBlocks(tokens, 'css'),
    ''
  ].join('\n');
}

/**
 * Tailwind v3 theme.extend object (values reference the CSS variables in tokens.css).
 * @param {Tokens} tokens
 * @returns {{ extend: Record<string, Record<string, string>>, skipped: string[] }}
 */
export function tailwindV3Theme(tokens) {
  /** @type {Record<string, Record<string, string>>} */
  const extend = {};
  /** @type {string[]} */
  const skipped = [];
  for (const [group, entries] of Object.entries(tokens.semantic)) {
    const g = GROUPS[group];
    if (!g) {
      skipped.push(group);
      continue;
    }
    for (const key of Object.keys(entries)) {
      const path = `semantic.${group}.${key}`;
      let section = g.v3;
      if (g.kind === 'motion') section = isDuration(resolveToken(tokens, path, tokens.themes[0])) ? 'transitionDuration' : 'transitionTimingFunction';
      if (!section) continue;
      (extend[section] ??= {})[key] = g.literal ? String(resolveToken(tokens, path, tokens.themes[0])) : `var(${varName(tokens, path, 'css')})`;
    }
  }
  return { extend, skipped };
}

/**
 * @param {Tokens} tokens
 * @param {'cjs' | 'esm'} format
 * @returns {string}
 */
export function emitTailwindV3(tokens, format) {
  const { extend, skipped } = tailwindV3Theme(tokens);
  const body = JSON.stringify({ theme: { extend } }, null, 2);
  return [
    `// ${HEADER}. Source: ${tokens.name}.`,
    '// Tailwind CSS v3 preset: add it to "presets" in tailwind.config and import tokens.css once',
    '// in your global stylesheet; every value is a var() so light/dark switching stays in CSS.',
    '// Opacity modifiers (bg-surface/50) do not apply to var() colors in v3.',
    ...(skipped.length ? [`// Semantic groups without a Tailwind mapping (use the CSS variables directly): ${skipped.join(', ')}.`] : []),
    '/** @type {import(\'tailwindcss\').Config} */',
    format === 'cjs' ? `module.exports = ${body};` : `export default ${body};`,
    ''
  ].join('\n');
}

/**
 * Tailwind v4 stylesheet: self-contained (use instead of tokens.css). Semantic tokens are
 * declared in @theme under Tailwind's namespaces; theme overrides redefine the same names.
 * @param {Tokens} tokens
 * @returns {string}
 */
export function emitTailwindV4(tokens) {
  const first = tokens.themes[0];
  /** Tokens that go in @theme: groups with a v4 namespace, and easing curves (durations have none). */
  const mapped = (/** @type {string} */ g, /** @type {string} */ k) => Boolean(GROUPS[g]?.v4 || (GROUPS[g]?.kind === 'motion' && !isDuration(resolveToken(tokens, `semantic.${g}.${k}`, first))));
  const themeDecl = [];
  for (const [group, entries] of Object.entries(tokens.semantic)) {
    for (const [key, value] of Object.entries(entries)) {
      if (!mapped(group, key)) continue;
      const path = `semantic.${group}.${key}`;
      const raw = value !== null && typeof value === 'object' ? /** @type {Record<string, string | number>} */ (value)[first] : value;
      const v = GROUPS[group].literal ? String(resolveToken(tokens, path, first)) : cssValue(tokens, raw, 'v4');
      themeDecl.push(`  ${varName(tokens, path, 'v4')}: ${v};`);
    }
  }
  return [
    `/* ${HEADER}. Source: ${tokens.name}.`,
    '   Tailwind CSS v4: @import "tailwindcss"; then @import this file. Use it instead of tokens.css.',
    '   Tailwind\'s default theme stays available; this file adds no palette of its own. */',
    '',
    ':root {',
    ...declarations(tokens, 'primitive', first, 'v4', false),
    ...declarations(tokens, 'semantic', first, 'v4', false, (g, k) => !mapped(g, k)),
    ...declarations(tokens, 'component', first, 'v4', false),
    '}',
    '',
    '@theme {',
    ...themeDecl,
    '}',
    ...themeBlocks(tokens, 'v4'),
    ''
  ].join('\n');
}

/**
 * Build every output file. Callers validate the schema first.
 * @param {Tokens} tokens
 * @returns {{ files: OutFile[], problems: string[] }}
 */
export function buildTokens(tokens) {
  const problems = buildProblems(tokens);
  if (problems.length) return { files: [], problems };
  return {
    problems: [],
    files: [
      { name: 'tokens.css', content: emitCss(tokens) },
      { name: 'tailwind.v3.cjs', content: emitTailwindV3(tokens, 'cjs') },
      { name: 'tailwind.v3.mjs', content: emitTailwindV3(tokens, 'esm') },
      { name: 'tailwind.v4.css', content: emitTailwindV4(tokens) }
    ]
  };
}
