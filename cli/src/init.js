// craft init: copy templates into .craft/ without overwriting anything.
import { existsSync, mkdirSync, copyFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const TEMPLATE_FILES = ['DESIGN.md', 'tokens.json', 'decisions.md', 'craft.config.json'];

/** @returns {string} */
export function templatesDir() {
  const dir = join(here, '..', '..', 'templates');
  if (!existsSync(join(dir, 'DESIGN.md'))) throw new Error(`Templates not found at ${dir}. Reinstall the skill package.`);
  return dir;
}

/**
 * @param {string} root project root
 * @returns {{ created: string[], skipped: string[] }}
 */
export function init(root) {
  const target = join(root, '.craft');
  mkdirSync(join(target, 'reports'), { recursive: true });
  /** @type {string[]} */
  const created = [];
  /** @type {string[]} */
  const skipped = [];
  const src = templatesDir();
  for (const f of TEMPLATE_FILES) {
    const dest = join(target, f);
    if (existsSync(dest)) {
      skipped.push(`.craft/${f}`);
      continue;
    }
    copyFileSync(src + '/' + f, dest);
    created.push(`.craft/${f}`);
  }
  const ignore = join(target, '.gitignore');
  if (!existsSync(ignore)) {
    writeFileSync(ignore, '# Proof reports are regenerated by craft report; do not commit them.\nreports/\n');
    created.push('.craft/.gitignore');
  } else {
    skipped.push('.craft/.gitignore');
  }
  return { created, skipped };
}
