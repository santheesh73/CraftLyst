#!/usr/bin/env node
// Generates the catalog provenance section of NOTICE.md from catalog/entries. Everything
// outside the BEGIN/END markers is kept verbatim. Modes:
//   (default)  rewrite NOTICE.md in place
//   --stdout   print the generated NOTICE.md, write nothing
//   --check    exit 1 if NOTICE.md differs from the generated text (CI)
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadCatalog, bundlesThirdPartyCode, SPDX_ALLOWLIST } from '../cli/src/catalog.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const BEGIN = '<!-- BEGIN catalog provenance: generated by scripts/generate-notice.js from catalog/entries; do not edit by hand -->';
export const END = '<!-- END catalog provenance -->';

/** @param {string} s */
const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');

/**
 * @param {import('../cli/src/catalog.js').LoadedEntry[]} loaded
 * @returns {string} the section between the markers (without them)
 */
export function provenanceSection(loaded) {
  const entries = loaded.flatMap((l) => (l.entry ? [l.entry] : [])).sort((a, b) => String(a.id).localeCompare(String(b.id)));
  const bundled = entries.filter(bundlesThirdPartyCode);
  const original = entries.filter((e) => e.source?.kind === 'original-spec');
  const references = entries.filter((e) => e.source?.kind !== 'original-spec' && !bundlesThirdPartyCode(e));
  const lines = ['### Catalog provenance', ''];
  if (bundled.length) {
    lines.push(`Third-party code bundled through catalog entries (SPDX allowlist: ${SPDX_ALLOWLIST.join(', ')}):`, '', '| Entry | Attribution | License (SPDX) | Source |', '|---|---|---|---|');
    for (const e of bundled) lines.push(`| ${e.id} | ${cell(e.source.attribution)} | ${cell(e.license.name)} (${e.license.spdx}) | ${e.source.url} |`);
  } else {
    lines.push(`No catalog entry bundles third-party code. Only SPDX ids on the allowlist (${SPDX_ALLOWLIST.join(', ')}) may be bundled; \`scripts/check-licenses.js\` enforces this in CI.`);
  }
  lines.push('', 'Runtime npm packages vendored into the installable package are listed with their licenses in `cli/THIRD-PARTY.md` inside the package (written by `scripts/package.js`).', '');
  const originalLicenses = [...new Set(original.map((e) => e.license?.spdx ?? e.license?.name))].sort();
  lines.push(`Original specifications: ${original.length} catalog entr${original.length === 1 ? 'y' : 'ies'} authored by ${[...new Set(original.map((e) => e.source.attribution))].sort().join(', ') || 'nobody yet'}${originalLicenses.length ? `, licensed ${originalLicenses.join(', ')}` : ''}.`);
  if (references.length) {
    lines.push('', 'Third-party references (metadata and links only, no code or copy bundled):', '', '| Entry | Trust | Attribution | License | Source |', '|---|---|---|---|---|');
    for (const e of references) lines.push(`| ${e.id} | ${e.trust} | ${cell(e.source.attribution)} | ${cell(e.license.name)}${e.license.spdx ? ` (${e.license.spdx})` : ''}, ${e.license.redistribution} | ${e.source.url ?? 'URL not verified'} |`);
  } else {
    lines.push('', 'Third-party references (link-only or gallery entries): none.');
  }
  return lines.join('\n');
}

/**
 * @param {string} notice current NOTICE.md
 * @param {string} section
 */
export function renderNotice(notice, section) {
  const b = notice.indexOf(BEGIN);
  const e = notice.indexOf(END);
  if (b < 0 || e < b) throw new Error(`NOTICE.md has no generated section. Add the lines\n${BEGIN}\n${END}\nwhere the catalog provenance should go.`);
  return `${notice.slice(0, b + BEGIN.length)}\n${section}\n${notice.slice(e)}`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const file = join(root, 'NOTICE.md');
  const current = readFileSync(file, 'utf8');
  const next = renderNotice(current, provenanceSection(loadCatalog({ catalogRoot: join(root, 'catalog') })));
  if (args.includes('--stdout')) process.stdout.write(next);
  else if (args.includes('--check')) {
    if (next !== current) {
      console.error('NOTICE.md is out of date with catalog provenance. Run "node scripts/generate-notice.js" and commit the result.');
      process.exit(1);
    }
    console.log('NOTICE.md is up to date with catalog provenance.');
  } else {
    writeFileSync(file, next);
    console.log(next === current ? 'NOTICE.md unchanged.' : 'NOTICE.md updated.');
  }
}
