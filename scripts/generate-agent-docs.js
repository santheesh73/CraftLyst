#!/usr/bin/env node
// Generates the agent tables from adapter data (adapters/<id>/adapter.json) and recorded
// verification results (adapters/verification.json):
//   - adapters/README.md (whole file)
//   - the agent section of docs/compatibility.md (between the markers; the rest is kept verbatim)
// Modes:
//   (default)  rewrite both files
//   --check    exit 1 if either file differs from the generated text (CI)
import { readFileSync, writeFileSync, realpathSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadAdapters } from '../installer/main.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const BEGIN = '<!-- BEGIN agents: generated by scripts/generate-agent-docs.js from adapters/; do not edit by hand -->';
export const END = '<!-- END agents -->';

/** @param {unknown} s */
const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
/** @param {string | null} p */
const code = (p) => (p ? `\`${p}\`` : 'n/a');

/**
 * @typedef {{ result: 'pass' | 'fail' | 'not-run', date?: string, tool?: string, command?: string, evidence?: string, reason?: string }} Check
 * @typedef {{ agents: Record<string, { v2?: Check, v3?: Check }>, defaultV2Reason: string, researchedNotSupported: { label: string, reason: string }[] }} Verification
 */

/** @returns {Verification} */
export function loadVerification() {
  return JSON.parse(readFileSync(join(root, 'adapters', 'verification.json'), 'utf8'));
}

/** @param {Check | undefined} c @param {string} pending */
function mark(c, pending) {
  if (!c || c.result === 'not-run') return pending;
  return c.result === 'pass' ? `✅ ${c.date}` : `❌ ${c.date}`;
}

/** @param {{ v2?: Check, v3?: Check } | undefined} rec */
export const statusLabel = (rec) => (rec?.v3?.result === 'pass' ? 'Supported' : 'Installed, behavior unverified');

/**
 * @param {import('../installer/main.js').Adapter[]} adapters
 * @param {Verification} ver
 * @param {string} linkBase prefix that turns "adapters/x" paths into links relative to the output file
 */
export function agentSection(adapters, ver, linkBase) {
  const rows = adapters.map((a) => {
    const rec = ver.agents[a.id];
    const names = [`\`${a.id}\``, ...a.aliases.map((x) => `\`${x}\``)].join(', ');
    const docs = a.docsUrl ? `[docs](${a.docsUrl}) (read ${a.docsVerifiedOn ?? 'not verified'})` : 'no vendor docs (open convention)';
    return `| [${cell(a.label)}](${linkBase}${a.id}/adapter.json) | ${names} | ${a.kind} | ${code(a.project)} | ${code(a.user)} | ${docs} | ✅ | ${mark(rec?.v2, '⚠️')} | ${mark(rec?.v3, 'pending')} | ${statusLabel(rec)} |`;
  });
  const v2 = adapters
    .map((a) => {
      const c = ver.agents[a.id]?.v2;
      if (c && c.result !== 'not-run') return `- ${a.label}: ${c.result === 'pass' ? '✅' : '❌'} \`${cell(c.command)}\` with ${cell(c.tool)} on ${c.date}: ${cell(c.evidence)}.`;
      return `- ${a.label}: ⚠️ not run: ${cell(c?.reason ?? ver.defaultV2Reason)}.`;
    })
    .join('\n');
  const caveats = adapters
    .filter((a) => a.caveats?.length)
    .map((a) => (a.caveats ?? []).map((c) => `- ${a.label}: ${c}`).join('\n'))
    .join('\n');
  const notSupported = ver.researchedNotSupported.map((x) => `| ${cell(x.label)} | ${cell(x.reason)} |`).join('\n');
  return `| Agent | \`--agent\` names | Kind | Project path | User path | Official docs | V1 | V2 | V3 | Status |
|---|---|---|---|---|---|---|---|---|---|
${rows.join('\n')}

- **V1, placement**: the installer put every file in place and \`node install.mjs verify\` passes. Checked automatically for every agent by \`scripts/test/installer.test.js\` and \`scripts/test/installer-e2e.test.js\` on Linux, macOS, and Windows.
- **V2, load check**: the agent's own CLI, run headlessly, lists the installed skill. ⚠️ means it was not run; the reason is below.
- **V3, behavior**: a person ran \`evals/agent-smoke/\` in that agent and recorded the result. This is a HUMAN GATE.
- **Supported** needs V1 and V3. **Installed, behavior unverified** means the files are in the place the agent's docs name, but nobody has yet watched the agent use them.
- Kind: \`skill\` copies the whole skill (Agent Skills format, \`SKILL.md\`); \`block\` adds a managed block to a shared file; \`file\` writes a managed rule file. Block and file kinds point the agent at the shared copy in \`.frontend-craft/\`.

### V2 results

${v2}

### Caveats

${caveats}

### Researched, not supported

| Agent | Reason |
|---|---|
${notSupported}

Research notes with the doc quotes: [docs/research/agent-docs.md](${linkBase}../docs/research/agent-docs.md).`;
}

/** @param {import('../installer/main.js').Adapter[]} adapters @param {Verification} ver */
export function adaptersReadme(adapters, ver) {
  return `# Agent adapters

<!-- Generated by scripts/generate-agent-docs.js from adapters/*/adapter.json and adapters/verification.json; do not edit by hand. -->

Each agent is one data file, \`adapters/<id>/adapter.json\`, validated against
[\`adapter-schema.json\`](adapter-schema.json). The installer, \`list\`, \`verify\`, and these tables
are all generated from those files. To add an agent: add one adapter file (from the agent's
official docs, with \`docsUrl\` and \`docsVerifiedOn\`), one test, and run
\`node scripts/generate-agent-docs.js\`.

Install: \`node install.mjs install --agent <names|auto|all> [--scope project|user] [--target <dir>]\`.
See [docs/installation.md](../docs/installation.md).

${agentSection(adapters, ver, '')}

Claude Code also ships optional hooks in [\`claude-code/hooks/\`](claude-code/hooks/); see
[\`claude-code/README.md\`](claude-code/README.md).
`;
}

/** @param {string} text @param {string} section */
export function spliceCompat(text, section) {
  const b = text.indexOf(BEGIN);
  const e = text.indexOf(END);
  if (b < 0 || e < b) throw new Error(`docs/compatibility.md needs the markers:\n${BEGIN}\n${END}`);
  return `${text.slice(0, b + BEGIN.length)}\n${section}\n${text.slice(e)}`;
}

/** @param {string} s */
const lf = (s) => s.replace(/\r\n/g, '\n');

function run() {
  const check = process.argv.includes('--check');
  const adapters = loadAdapters(root);
  const ver = loadVerification();
  for (const id of Object.keys(ver.agents)) {
    if (!adapters.some((a) => a.id === id)) throw new Error(`adapters/verification.json names unknown agent "${id}"`);
  }
  const compatPath = join(root, 'docs', 'compatibility.md');
  const readmePath = join(root, 'adapters', 'README.md');
  const outputs = [
    [readmePath, adaptersReadme(adapters, ver)],
    [compatPath, spliceCompat(lf(readFileSync(compatPath, 'utf8')), agentSection(adapters, ver, '../adapters/'))],
  ];
  let stale = 0;
  for (const [path, want] of outputs) {
    const have = lf(readFileSync(path, 'utf8'));
    if (have === want) continue;
    if (check) {
      stale++;
      process.stderr.write(`${path} is out of date: run node scripts/generate-agent-docs.js\n`);
    } else {
      writeFileSync(path, want);
      process.stdout.write(`wrote ${path}\n`);
    }
  }
  process.exitCode = stale ? 1 : 0;
}

if (process.argv[1] && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))) run();
